def test_postgres_connection_transaction_and_migrations(postgres_runtime) -> None:
    from packages.common.pg_runtime import (
        PostgresMigration,
        apply_schema_migrations,
        connect_postgres,
        postgres_transaction,
    )

    schema = "test_" + uuid.uuid4().hex[:16]

    def initial(conn) -> None:
        conn.execute(
            "CREATE TABLE migration_probe ("
            "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "occurred_at timestamptz NOT NULL, payload jsonb NOT NULL, body text NOT NULL, "
            "body_search tsvector GENERATED ALWAYS AS (to_tsvector('simple', body)) STORED)"
        )
        conn.execute("CREATE INDEX migration_probe_search ON migration_probe USING gin (body_search)")
        conn.execute("CREATE TABLE migration_probe_audit (probe_id bigint NOT NULL)")
        conn.execute(
            "CREATE FUNCTION migration_probe_audit_insert() RETURNS trigger LANGUAGE plpgsql AS "
            "$$ BEGIN INSERT INTO migration_probe_audit(probe_id) VALUES (NEW.id); RETURN NEW; END $$"
        )
        conn.execute(
            "CREATE TRIGGER migration_probe_audit_after_insert AFTER INSERT ON migration_probe "
            "FOR EACH ROW EXECUTE FUNCTION migration_probe_audit_insert()"
        )

    migration = PostgresMigration(1, "initial", "sha256:test-initial-v1", initial)
    with connect_postgres(
        application_name="odaily-pg-integration-test",
        search_path=(schema,),
        settings=postgres_runtime,
    ) as connection:
        assert connection.autocommit is True
        connection.execute("SET TIME ZONE 'UTC'")
        assert connection.execute("SELECT 1 AS value").fetchone() == {"value": 1}
        assert connection.info.transaction_status.name == "IDLE"

        assert apply_schema_migrations(connection, schema=schema, migrations=(migration,), settings=postgres_runtime) == (1,)
        assert apply_schema_migrations(connection, schema=schema, migrations=(migration,), settings=postgres_runtime) == ()
        assert connection.execute("SELECT current_schema() AS schema").fetchone() == {"schema": schema}
        assert connection.execute(
            "SELECT table_schema FROM information_schema.tables WHERE table_name = 'migration_probe' AND table_schema = %s",
            (schema,),
        ).fetchone() == {"table_schema": schema}
        with pytest.raises(RuntimeError, match="changed"):
            apply_schema_migrations(
                connection,
                schema=schema,
                migrations=(PostgresMigration(1, "initial", "changed", initial),),
                settings=postgres_runtime,
            )

        with pytest.raises(RuntimeError, match="force rollback"):
            with postgres_transaction(connection):
                from psycopg.types.json import Jsonb

                connection.execute(
                    "INSERT INTO migration_probe (occurred_at, payload, body) VALUES (%s, %s, %s)",
                    (datetime.now(timezone.utc), Jsonb({"k": "v"}), "rollback probe"),
                )
                raise RuntimeError("force rollback")
        assert connection.execute("SELECT count(*) AS count FROM migration_probe").fetchone() == {"count": 0}

        from psycopg.types.json import Jsonb

        with postgres_transaction(connection):
            inserted = connection.execute(
                "INSERT INTO migration_probe (occurred_at, payload, body) VALUES (%s, %s, %s) RETURNING id",
                (datetime(2026, 1, 1, tzinfo=timezone.utc), Jsonb({"k": "v"}), "hello world"),
            ).fetchone()
        row = connection.execute(
            "SELECT id, occurred_at, payload, body_search @@ plainto_tsquery('simple', 'hello world') AS found "
            "FROM migration_probe WHERE id = %s",
            (inserted["id"],),
        ).fetchone()
        assert row["id"] == inserted["id"]
        assert row["occurred_at"].utcoffset().total_seconds() == 0
        assert row["payload"] == {"k": "v"}
        assert row["found"] is True
        assert connection.execute("SELECT probe_id FROM migration_probe_audit").fetchone() == {"probe_id": inserted["id"]}

    from packages.common.pg_native import connect_postgres as connect_scoped
    from psycopg.sql import Identifier

    with connect_scoped(schema=schema, application_name="odaily-pg-integration-test-queue", settings=postgres_runtime) as first:
        with connect_scoped(schema=schema, application_name="odaily-pg-integration-test-worker", settings=postgres_runtime) as second:
            first.execute("CREATE TABLE queue_probe (id integer PRIMARY KEY, status text NOT NULL)")
            first.execute("INSERT INTO queue_probe VALUES (1, 'pending'), (2, 'pending')")
            with first.transaction():
                claimed_one = first.execute(
                    "SELECT id FROM queue_probe WHERE status = 'pending' ORDER BY id FOR UPDATE SKIP LOCKED LIMIT 1"
                ).fetchone()
                claimed_two = second.execute(
                    "SELECT id FROM queue_probe WHERE status = 'pending' ORDER BY id FOR UPDATE SKIP LOCKED LIMIT 1"
                ).fetchone()
                assert claimed_one["id"] != claimed_two["id"]

    with connect_scoped(schema=schema, application_name="odaily-pg-role-one", settings=postgres_runtime) as pooled:
        assert pooled.execute("SELECT current_schema() AS schema").fetchone() == {"schema": schema}
        assert pooled.execute("SHOW TimeZone").fetchone() == {"TimeZone": "UTC"}
        assert pooled.execute("SELECT current_setting('application_name') AS app").fetchone() == {"app": "odaily-pg-role-one"}
        with pytest.raises(RuntimeError, match="pool rollback"):
            with pooled.transaction():
                pooled.execute("UPDATE queue_probe SET status = 'done' WHERE id = 1")
                raise RuntimeError("pool rollback")
        pooled.execute("SET search_path TO public")
        pooled.execute("SET TIME ZONE 'Pacific/Auckland'")
        pooled.execute("SET statement_timeout TO 0")

    with connect_scoped(schema=schema, application_name="odaily-pg-role-two", settings=postgres_runtime) as pooled:
        assert pooled.execute("SELECT current_schema() AS schema").fetchone() == {"schema": schema}
        assert pooled.execute("SHOW TimeZone").fetchone() == {"TimeZone": "UTC"}
        assert pooled.execute("SELECT current_setting('application_name') AS app").fetchone() == {"app": "odaily-pg-role-two"}
        assert pooled.execute("SHOW statement_timeout").fetchone()["statement_timeout"] != "0"
        assert pooled.execute("SELECT status FROM queue_probe WHERE id = 1").fetchone() == {"status": "pending"}

    from packages.common.pg_native import postgres_pool_stats

    stats = postgres_pool_stats()
    assert stats["size"] <= stats["capacity"]
    assert stats["borrowed"] == 0
    assert stats["waiting"] == 0

    # The schema is isolated to this test, and the DSN must point at a disposable test cluster.
    with connect_postgres(
        application_name="odaily-pg-integration-test-cleanup",
        settings=postgres_runtime,
    ) as cleanup:
        cleanup.execute("DELETE FROM main._odaily_schema_migrations WHERE schema_name = %s", (schema,))
        cleanup.execute("DROP SCHEMA IF EXISTS " + Identifier(schema).as_string(cleanup) + " CASCADE")


def test_postgres_migration_bootstrap_is_safe_across_schemas(postgres_runtime) -> None:
    from packages.common.pg_runtime import PostgresMigration, apply_schema_migrations
    from packages.common.pg_native import connect_postgres
    from psycopg.sql import Identifier

    schemas = ("test_" + uuid.uuid4().hex[:16], "test_" + uuid.uuid4().hex[:16])

    def apply(schema: str) -> tuple[str, tuple[int, ...]]:
        migration = PostgresMigration(
            1,
            "initial",
            f"sha256:{schema}",
            lambda conn: conn.execute("CREATE TABLE bootstrap_probe (id integer PRIMARY KEY)"),
        )
        with connect_postgres(schema=schema, settings=postgres_runtime) as connection:
            return schema, apply_schema_migrations(
                connection,
                schema=schema,
                migrations=(migration,),
                settings=postgres_runtime,
            )

    with ThreadPoolExecutor(max_workers=2) as executor:
        results = tuple(executor.map(apply, schemas))
    assert results == ((schemas[0], (1,)), (schemas[1], (1,)))

    with connect_postgres(schema="main", application_name="odaily-pg-integration-test-cleanup", settings=postgres_runtime) as cleanup:
        cleanup.execute("DELETE FROM main._odaily_schema_migrations WHERE schema_name = ANY(%s)", (list(schemas),))
        for schema in schemas:
            cleanup.execute("DROP SCHEMA IF EXISTS " + Identifier(schema).as_string(cleanup) + " CASCADE")


