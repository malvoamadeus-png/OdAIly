def test_postgres_source_state_trigger_is_transactional_and_allowlisted(postgres_runtime) -> None:
    from packages.common.pg_native import PostgresMigration, apply_schema_migrations, connect_postgres
    from packages.system_observability.postgres_schema import (
        SOURCE_STATE_CHECKSUM,
        SourceStateTriggerSpec,
        _install_source_state_schema,
        acknowledge_source_state_events,
        claim_source_state_events,
        install_source_state_trigger,
    )
    from psycopg.sql import Identifier

    table = "source_" + uuid.uuid4().hex[:16]
    with connect_postgres(schema="main", application_name="odaily-observability-trigger-test", settings=postgres_runtime) as connection:
        apply_schema_migrations(
            connection,
            schema="main",
            component="system_observability_source_outbox",
            migrations=(PostgresMigration(1, "source state outbox", SOURCE_STATE_CHECKSUM, _install_source_state_schema),),
            settings=postgres_runtime,
        )
        connection.execute(
            f"CREATE TABLE {Identifier('main', table).as_string(connection)} "
            "(id bigint PRIMARY KEY, status text NOT NULL, heartbeat_at timestamptz, api_key text)"
        )
        install_source_state_trigger(
            connection,
            SourceStateTriggerSpec(
                schema="main",
                table=table,
                row_id_columns=("id",),
                payload_columns=("status",),
            ),
        )
        with connection.transaction():
            connection.execute(f"INSERT INTO main.{Identifier(table).as_string(connection)} VALUES(1,'pending',NULL,'secret-value')")
        with connection.transaction():
            first = claim_source_state_events(connection, limit=10)
            matching = [event for event in first if event["source_table"] == table]
            assert len(matching) == 1
            assert matching[0]["payload"] == {"status": "pending"}
            event_id = matching[0]["event_id"]
            assert acknowledge_source_state_events(connection, [event_id]) == 1
        with pytest.raises(RuntimeError, match="active caller-owned"):
            claim_source_state_events(connection, limit=10)
        with pytest.raises(RuntimeError, match="active caller-owned"):
            acknowledge_source_state_events(connection, [event_id])
        connection.execute(
            f"UPDATE main.{Identifier(table).as_string(connection)} SET heartbeat_at=CURRENT_TIMESTAMP WHERE id=1"
        )
        with connection.transaction():
            assert [event for event in claim_source_state_events(connection, limit=10) if event["source_table"] == table] == []
        with pytest.raises(RuntimeError, match="rollback source update"):
            with connection.transaction():
                connection.execute(f"UPDATE main.{Identifier(table).as_string(connection)} SET status='failed' WHERE id=1")
                raise RuntimeError("rollback source update")
        with connection.transaction():
            assert [event for event in claim_source_state_events(connection, limit=10) if event["source_table"] == table] == []
        connection.execute(f"UPDATE main.{Identifier(table).as_string(connection)} SET status='success' WHERE id=1")
        with connection.transaction():
            created = [event for event in claim_source_state_events(connection, limit=10) if event["source_table"] == table]
            assert len(created) == 1 and created[0]["payload"] == {"status": "success"}
            assert acknowledge_source_state_events(connection, [created[0]["event_id"]]) == 1
        assert connection.execute(
            "SELECT projected_at IS NOT NULL AS acknowledged FROM main.odaily_source_state_outbox WHERE event_id=%s",
            (created[0]["event_id"],),
        ).fetchone()["acknowledged"] is True
        connection.execute(f"DROP TABLE main.{Identifier(table).as_string(connection)} CASCADE")
        connection.execute("DELETE FROM main.odaily_source_state_outbox WHERE source_table=%s", (table,))


def test_postgres_outbox_pending_scan_handles_commit_order_gaps(postgres_runtime) -> None:
    from packages.common.pg_native import connect_postgres
    from packages.system_observability.postgres_schema import acknowledge_source_state_events, claim_source_state_events

    with connect_postgres(schema="main", application_name="odaily-outbox-order-a", settings=postgres_runtime) as first:
        with connect_postgres(schema="main", application_name="odaily-outbox-order-b", settings=postgres_runtime) as second:
            first_tx = first.transaction()
            first_tx.__enter__()
            first_id = first.execute(
                "INSERT INTO main.odaily_source_state_outbox(source_schema,source_table,source_row_id,operation,payload) "
                "VALUES('main','commit_order_probe','first','INSERT','{}'::jsonb) RETURNING event_id"
            ).fetchone()["event_id"]
            with second.transaction():
                second_id = second.execute(
                    "INSERT INTO main.odaily_source_state_outbox(source_schema,source_table,source_row_id,operation,payload) "
                    "VALUES('main','commit_order_probe','second','INSERT','{}'::jsonb) RETURNING event_id"
                ).fetchone()["event_id"]
            assert first_id < second_id

            with second.transaction():
                claimed = claim_source_state_events(second, limit=10)
                assert [row["event_id"] for row in claimed] == [second_id]
                assert acknowledge_source_state_events(second, [second_id]) == 1

            first_tx.__exit__(None, None, None)
            with second.transaction():
                claimed = claim_source_state_events(second, limit=10)
                assert [row["event_id"] for row in claimed] == [first_id]
                assert acknowledge_source_state_events(second, [first_id]) == 1
            second.execute("DELETE FROM main.odaily_source_state_outbox WHERE event_id=ANY(%s)", ([first_id, second_id],))


def test_postgres_small_evidence_is_content_addressed(postgres_runtime, monkeypatch) -> None:
    import gzip
    import hashlib

    from packages.system_observability.postgres_evidence import PostgresSmallEvidenceStore
    from psycopg.sql import Identifier
    from packages.common.pg_native import connect_postgres

    schema = "test_evidence_" + uuid.uuid4().hex[:12]
    monkeypatch.setattr(
        "packages.system_observability.postgres_evidence.connect_postgres",
        lambda **kwargs: connect_postgres(**{**kwargs, "settings": kwargs.get("settings") or postgres_runtime}),
    )
    store = PostgresSmallEvidenceStore(schema=schema)
    content = b"short evidence payload"
    reference = hashlib.sha256(content).hexdigest()
    compressed = gzip.compress(content, mtime=0)
    try:
        store.initialize(settings=postgres_runtime)
        assert store.put(reference, compressed, uncompressed_size=len(content)) is True
        assert store.put(reference, compressed, uncompressed_size=len(content)) is False
        assert store.get(reference) == compressed
        from packages.common.pg_native import connect_postgres as connect_native
        with connect_native(schema=schema, application_name="odaily-evidence-test", settings=postgres_runtime) as connection:
            with pytest.raises(RuntimeError, match="active caller-owned"):
                store.lock_for_reference(connection, reference)
            with connection.transaction():
                store.lock_for_reference(connection, reference)
        with pytest.raises(Exception, match="does not match"):
            store.put(reference, gzip.compress(b"different"), uncompressed_size=9)
        assert store.delete_if_unreferenced(reference) is True
        assert store.get(reference) is None
    finally:
        with connect_postgres(schema="main", settings=postgres_runtime) as cleanup:
            cleanup.execute("DELETE FROM main._odaily_schema_migrations WHERE schema_name=%s AND component='system_observability_evidence'", (schema,))
            cleanup.execute("DROP SCHEMA IF EXISTS " + Identifier(schema).as_string(cleanup) + " CASCADE")
