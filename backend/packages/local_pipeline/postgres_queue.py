from __future__ import annotations

import json
import hashlib
import uuid
from datetime import UTC, datetime, timedelta
from typing import Any

from packages.common.pg_native import PostgresMigration, apply_schema_migrations, connect_postgres
from packages.common.storage import load_postgres_settings, load_storage_settings

from .queue import LocalPipelineJob, LocalPipelineJobType, decode_payload, utc_now

_QUEUE_SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS local_pipeline_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type text NOT NULL CHECK (job_type IN ('write_flow', 'alert_only')),
    task_id bigint NOT NULL,
    source text NOT NULL,
    source_item_id text NOT NULL,
    status text NOT NULL DEFAULT 'pending',
    attempt_count integer NOT NULL DEFAULT 0,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    storage_epoch text NOT NULL DEFAULT 'postgres-legacy',
    locked_by text,
    locked_at timestamptz,
    lease_token text,
    next_attempt_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(source, source_item_id)

);
"""
_QUEUE_SCHEMA_SQL += "\nCREATE INDEX IF NOT EXISTS idx_local_pipeline_jobs_ready ON local_pipeline_jobs(storage_epoch, status, next_attempt_at, created_at, id);\n"
_QUEUE_SCHEMA_SQL += "CREATE INDEX IF NOT EXISTS idx_local_pipeline_jobs_lease ON local_pipeline_jobs(storage_epoch, locked_at) WHERE status = 'running';"
_QUEUE_SCHEMA_CHECKSUM = hashlib.sha256(_QUEUE_SCHEMA_SQL.encode("utf-8")).hexdigest()


class PostgresLocalPipelineQueue:
    """PostgreSQL queue with fenced leases for local_pipeline workers."""

    def __init__(self, *, storage_epoch: str | None = None, max_attempts: int = 3, schema: str = "local_pipeline") -> None:
        if max_attempts < 1:
            raise ValueError("max_attempts must be at least 1")
        self.storage_epoch = storage_epoch or load_storage_settings().epoch
        self.max_attempts = max_attempts
        self.schema = schema
        self.init_schema()

    def _connect(self, role: str):
        return connect_postgres(schema=self.schema, application_name=f"odaily-local-pipeline-{role}")

    @staticmethod
    def _migration(conn) -> None:
        for statement in _QUEUE_SCHEMA_SQL.split(";"):
            if statement.strip():
                conn.execute(statement)

    def init_schema(self) -> None:
        self.initialize_schema(schema=self.schema)

    @staticmethod
    def initialize_schema(*, schema: str = "local_pipeline") -> None:
        with connect_postgres(schema=schema, application_name="odaily-local-pipeline-migrate") as conn:
            apply_schema_migrations(
                conn,
                schema=schema,
                component="local_pipeline",
                migrations=(PostgresMigration(1, "local pipeline jobs", _QUEUE_SCHEMA_CHECKSUM, PostgresLocalPipelineQueue._migration),),
                settings=load_postgres_settings(),
            )

    @staticmethod
    def _job(row) -> LocalPipelineJob:
        payload = row["payload"]
        if not isinstance(payload, dict):
            payload = decode_payload(payload)
        return LocalPipelineJob(
            id=int(row["id"]), job_type=row["job_type"], task_id=int(row["task_id"]),
            source=row["source"], source_item_id=row["source_item_id"], status=row["status"],
            attempt_count=int(row["attempt_count"]), payload=payload,
            storage_epoch=row["storage_epoch"], lease_token=row["lease_token"],
        )

    def enqueue(self, *, job_type: LocalPipelineJobType, task_id: int, source: str,
                source_item_id: str, payload: dict[str, Any] | None = None) -> LocalPipelineJob:
        now = utc_now()
        with self._connect("enqueue") as conn:
            with conn.transaction():
                conn.execute("""
                    INSERT INTO local_pipeline_jobs(job_type,task_id,source,source_item_id,payload,storage_epoch,status,next_attempt_at,updated_at)
                    VALUES(%s,%s,%s,%s,%s,%s,'pending',%s,%s)
                    ON CONFLICT(source,source_item_id) DO UPDATE SET
                        job_type=CASE WHEN local_pipeline_jobs.status='running' THEN local_pipeline_jobs.job_type ELSE excluded.job_type END,
                        task_id=CASE WHEN local_pipeline_jobs.status='running' THEN local_pipeline_jobs.task_id ELSE excluded.task_id END,
                        payload=CASE WHEN local_pipeline_jobs.status='running' THEN local_pipeline_jobs.payload ELSE excluded.payload END,
                        status=CASE WHEN local_pipeline_jobs.status IN ('succeeded','running') THEN local_pipeline_jobs.status ELSE 'pending' END,
                        next_attempt_at=CASE WHEN local_pipeline_jobs.status IN ('succeeded','running') THEN local_pipeline_jobs.next_attempt_at ELSE excluded.next_attempt_at END,
                        updated_at=excluded.updated_at
                    WHERE local_pipeline_jobs.storage_epoch=excluded.storage_epoch
                """, (job_type, task_id, source, source_item_id, json.dumps(payload or {}, ensure_ascii=False), self.storage_epoch, now, now))
                row = conn.execute("SELECT * FROM local_pipeline_jobs WHERE source=%s AND source_item_id=%s", (source, source_item_id)).fetchone()
        return self._job(row)

    def adopt_frozen_sqlite_epoch(self, *, source_epoch: str = "sqlite-primary",
                                  source_writes_stopped: bool = False) -> dict[str, Any]:
        """Explicitly move imported queue identity into this PG epoch after SQLite is frozen.

        Job state and leases are preserved. Running jobs remain fenced and are only
        retried by the normal stale-lease recovery path after its timeout.
        """
        if not source_writes_stopped:
            raise RuntimeError("confirm all SQLite local_pipeline writers are stopped before epoch adoption")
        if source_epoch != "sqlite-primary":
            raise ValueError("only the frozen sqlite-primary epoch can be adopted")
        if source_epoch == self.storage_epoch:
            raise ValueError("source and destination storage epochs must differ")
        with self._connect("epoch-adopt") as conn:
            with conn.transaction():
                rows = conn.execute(
                    "SELECT status,count(*) AS count FROM local_pipeline_jobs WHERE storage_epoch=%s GROUP BY status ORDER BY status",
                    (source_epoch,),
                ).fetchall()
                result = conn.execute(
                    "UPDATE local_pipeline_jobs SET storage_epoch=%s WHERE storage_epoch=%s",
                    (self.storage_epoch, source_epoch),
                )
        return {
            "source_epoch": source_epoch,
            "destination_epoch": self.storage_epoch,
            "adopted": result.rowcount or 0,
            "source_status_counts": {str(row["status"]): int(row["count"]) for row in rows},
        }

    def claim_next(self, *, worker_id: str) -> LocalPipelineJob | None:
        now = utc_now()
        token = uuid.uuid4().hex
        with self._connect("claim") as conn:
            with conn.transaction():
                row = conn.execute("""
                    SELECT id FROM local_pipeline_jobs
                    WHERE status IN ('pending','failed') AND attempt_count < %s
                      AND storage_epoch=%s AND next_attempt_at <= %s
                    ORDER BY created_at,id LIMIT 1 FOR UPDATE SKIP LOCKED
                """, (self.max_attempts, self.storage_epoch, now)).fetchone()
                if row is None:
                    return None
                claimed = conn.execute("""
                    UPDATE local_pipeline_jobs SET status='running',attempt_count=attempt_count+1,
                        locked_by=%s,locked_at=%s,lease_token=%s,updated_at=%s
                    WHERE id=%s RETURNING *
                """, (worker_id, now, token, now, row["id"])).fetchone()
        return self._job(claimed)

    def requeue_stale_running_jobs(self, *, stale_before: datetime, exclude_worker_id: str | None = None) -> int:
        now = utc_now()
        with self._connect("recover") as conn:
            result = conn.execute("""
                UPDATE local_pipeline_jobs SET
                    status=CASE WHEN attempt_count >= %s THEN 'exhausted' ELSE 'failed' END,
                    locked_by=NULL,locked_at=NULL,lease_token=NULL,
                    last_error=CASE WHEN coalesce(last_error,'')='' THEN 'stale running job requeued after worker restart'
                        ELSE left(last_error,1800) || E'\\n[stale running job requeued after worker restart]' END,
                    next_attempt_at=%s,updated_at=%s
                WHERE status='running' AND storage_epoch=%s AND locked_at < %s
                  AND (%s::text IS NULL OR locked_by IS NULL OR locked_by <> %s)
            """, (self.max_attempts, now, now, self.storage_epoch, stale_before, exclude_worker_id, exclude_worker_id))
            return result.rowcount or 0

    def mark_succeeded(self, job_id: int, *, lease_token: str | None = None) -> bool:
        if not lease_token:
            raise ValueError("lease_token is required to complete a PostgreSQL queue job")
        with self._connect("complete") as conn:
            result = conn.execute("""
                UPDATE local_pipeline_jobs SET status='succeeded',locked_by=NULL,locked_at=NULL,
                    lease_token=NULL,last_error=NULL,updated_at=%s
                WHERE id=%s AND status='running' AND storage_epoch=%s AND lease_token=%s
            """, (utc_now(), job_id, self.storage_epoch, lease_token))
            return bool(result.rowcount)

    def mark_failed(self, job_id: int, *, error: str, attempt_count: int, lease_token: str | None = None) -> bool:
        if not lease_token:
            raise ValueError("lease_token is required to fail a PostgreSQL queue job")
        delay = min(300, max(5, 2 ** min(attempt_count, 8)))
        now = utc_now()
        next_attempt = now + timedelta(seconds=delay)
        with self._connect("fail") as conn:
            result = conn.execute("""
                UPDATE local_pipeline_jobs SET
                    status=CASE WHEN %s >= %s THEN 'exhausted' ELSE 'failed' END,
                    locked_by=NULL,locked_at=NULL,lease_token=NULL,last_error=%s,
                    next_attempt_at=CASE WHEN %s >= %s THEN %s ELSE %s END,updated_at=%s
                WHERE id=%s AND status='running' AND storage_epoch=%s AND lease_token=%s
            """, (attempt_count, self.max_attempts, error[:2000], attempt_count, self.max_attempts,
                  now, next_attempt, now, job_id, self.storage_epoch, lease_token))
            return bool(result.rowcount)

    def stats(self) -> dict[str, int]:
        with self._connect("stats") as conn:
            rows = conn.execute("SELECT status,count(*) AS count FROM local_pipeline_jobs WHERE storage_epoch=%s GROUP BY status", (self.storage_epoch,)).fetchall()
        return {row["status"]: int(row["count"]) for row in rows}

    def stats_by_epoch(self) -> dict[str, dict[str, int]]:
        with self._connect("stats") as conn:
            rows = conn.execute("SELECT storage_epoch,status,count(*) AS count FROM local_pipeline_jobs GROUP BY storage_epoch,status ORDER BY storage_epoch,status").fetchall()
        result: dict[str, dict[str, int]] = {}
        for row in rows:
            result.setdefault(row["storage_epoch"], {})[row["status"]] = int(row["count"])
        return result

    def list_over_limit_jobs(self) -> list[dict[str, Any]]:
        with self._connect("maintenance") as conn:
            return conn.execute("SELECT id,job_type,task_id,source,source_item_id,status,attempt_count,last_error,updated_at FROM local_pipeline_jobs WHERE storage_epoch=%s AND status IN ('failed','running') AND attempt_count >= %s ORDER BY updated_at,id", (self.storage_epoch, self.max_attempts)).fetchall()

    def exhaust_over_limit_jobs(self) -> int:
        with self._connect("maintenance") as conn:
            result = conn.execute("UPDATE local_pipeline_jobs SET status='exhausted',locked_by=NULL,locked_at=NULL,lease_token=NULL,next_attempt_at=%s,updated_at=%s WHERE storage_epoch=%s AND status='failed' AND attempt_count >= %s", (utc_now(), utc_now(), self.storage_epoch, self.max_attempts))
            return result.rowcount or 0

    def list_exhausted_jobs(self, *, limit: int = 5) -> list[dict[str, Any]]:
        with self._connect("maintenance") as conn:
            return conn.execute("SELECT id,job_type,task_id,source,source_item_id,attempt_count,last_error,updated_at FROM local_pipeline_jobs WHERE storage_epoch=%s AND status='exhausted' ORDER BY updated_at DESC,id DESC LIMIT %s", (self.storage_epoch, limit)).fetchall()


def create_local_pipeline_queue(path=None, *, max_attempts: int = 3):
    settings = load_storage_settings()
    if settings.backend == "postgres":
        return PostgresLocalPipelineQueue(max_attempts=max_attempts)
    if path is None:
        raise ValueError("SQLite local pipeline queue requires a database path")
    from .queue import LocalPipelineQueue

    return LocalPipelineQueue(path, storage_epoch=settings.epoch, max_attempts=max_attempts)
