    def prune_history(self, now: datetime | None = None) -> dict[str, int]:
        from datetime import timedelta
        from .retention import KEY_LEVEL, RETENTION_DAYS, TERMINAL
        cutoff=((now or datetime.now(UTC))-timedelta(days=RETENTION_DAYS)).isoformat()
        counts: dict[str,int]={}
        with connect_postgres(schema=self.schema,application_name="odaily-meme-retention") as conn:
            with conn.transaction():
                conn.execute("""CREATE TABLE IF NOT EXISTS key_breakthrough_results(
                    trigger_key text PRIMARY KEY,status text NOT NULL,reason text,title text,completed_at text)""")
                cursor=conn.execute(f"""INSERT INTO key_breakthrough_results
                    SELECT j.trigger_key,j.status,j.reason,j.title,COALESCE(j.completed_at,j.updated_at)
                    FROM jobs j JOIN market_cap_milestones m ON m.trigger_key=j.trigger_key
                    WHERE m.level >= %s AND j.status IN {TERMINAL} AND COALESCE(j.completed_at,j.updated_at)<%s
                    ON CONFLICT(trigger_key) DO UPDATE SET status=excluded.status,reason=excluded.reason,title=excluded.title,completed_at=excluded.completed_at""",(KEY_LEVEL,cutoff))
                cursor=conn.execute(f"DELETE FROM jobs WHERE status IN {TERMINAL} AND COALESCE(completed_at,updated_at)<%s",(cutoff,)); counts['jobs']=cursor.rowcount
                conn.execute("UPDATE market_cap_milestones SET job_id=NULL WHERE job_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM jobs WHERE id=job_id)")
                cursor=conn.execute("""DELETE FROM tg_candidates c WHERE detected_at<%s AND NOT EXISTS
                    (SELECT 1 FROM jobs WHERE trigger_key='tg_burst:' || c.id::text)""",(cutoff,)); counts['tg_candidates']=cursor.rowcount
                cursor=conn.execute("DELETE FROM ca_mentions WHERE sent_at<%s",(cutoff,)); counts['ca_mentions']=cursor.rowcount
                cursor=conn.execute("""UPDATE observations SET platform='',symbol='',last_volume_24h=0,last_token_info_error=NULL,
                    token_info_failures=0,last_token_info_at=NULL,next_token_info_at=NULL,tracking_interval_seconds=NULL,last_completed_seen_at=NULL
                    WHERE tracking_status<>'active' AND last_seen_at<%s
                    AND (symbol<>'' OR last_token_info_error IS NOT NULL OR last_completed_seen_at IS NOT NULL)""",(cutoff,)); counts['observations']=cursor.rowcount
            removed=0
            while True:
                with conn.transaction():
                    n=conn.execute("""DELETE FROM token_snapshots WHERE id IN
                        (SELECT s.id FROM token_snapshots s WHERE observed_at<%s AND id NOT IN
                         (SELECT snapshot_id FROM market_cap_milestones WHERE level>=%s) LIMIT 1000)""",(cutoff,KEY_LEVEL)).rowcount
                removed+=n
                if n<1000: break
            counts['token_snapshots']=removed
            conn.execute("""UPDATE market_cap_milestones SET snapshot_id=0 WHERE level<%s AND snapshot_id<>0
                AND NOT EXISTS(SELECT 1 FROM token_snapshots WHERE id=snapshot_id)""",(KEY_LEVEL,))
        return counts

