            with conn.transaction():
                conn.execute("UPDATE daily_hot_scans SET completed_at=%s,summary_json=%s WHERE id=%s", (completed_at, summary_json, run_id))
                conn.execute("DELETE FROM daily_hot_scans WHERE started_at < %s", (cutoff,))


