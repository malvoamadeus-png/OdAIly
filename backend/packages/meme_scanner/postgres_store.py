        delay=fomo_login_retry_seconds() if special else RETRY_DELAYS_SECONDS[min(attempts-1,len(RETRY_DELAYS_SECONDS)-1)]
        next_at=(datetime.now(UTC)+timedelta(seconds=delay)).isoformat(); stamp=now_iso()
