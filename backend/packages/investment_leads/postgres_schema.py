from __future__ import annotations

from hashlib import sha256

from packages.common.pg_native import PostgresMigration, apply_schema_migrations, connect_postgres
from packages.common.storage import PostgresSettings


INVESTMENT_LEADS_SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS investment_leads_meta (
  singleton_key text PRIMARY KEY CHECK (singleton_key='global'),
  capture_started_at timestamptz NOT NULL,
  worker_last_seen_at timestamptz,
  last_maintenance_at timestamptz,
  maintenance_next_at timestamptz,
  model_error text
);
CREATE TABLE IF NOT EXISTS investment_lead_maintenance_progress (
  stage text PRIMARY KEY CHECK (stage IN ('events','materials')),
  cursor_time timestamptz NOT NULL,
  cursor_id text NOT NULL,
  cursor_value text NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS investment_lead_materials (
  material_id text NOT NULL,
  content_hash text NOT NULL,
  posted_at timestamptz,
  activity_at timestamptz,
  activity_time_complete boolean NOT NULL DEFAULT false,
  relation text NOT NULL,
  payload_json jsonb NOT NULL,
  first_observed_at timestamptz NOT NULL,
  last_observed_at timestamptz NOT NULL,
  completeness text NOT NULL DEFAULT 'complete',
  PRIMARY KEY(material_id,content_hash)
);
CREATE INDEX IF NOT EXISTS idx_investment_material_recent ON investment_lead_materials(posted_at DESC,material_id);
CREATE INDEX IF NOT EXISTS idx_investment_material_expiry ON investment_lead_materials(last_observed_at,material_id,content_hash);
CREATE TABLE IF NOT EXISTS investment_lead_observations (
  material_id text NOT NULL,
  content_hash text NOT NULL,
  screen_name_lower text NOT NULL REFERENCES hottopic_accounts(screen_name_lower),
  relation text NOT NULL,
  first_observed_at timestamptz NOT NULL,
  last_observed_at timestamptz NOT NULL,
  PRIMARY KEY(material_id,content_hash,screen_name_lower,relation),
  FOREIGN KEY(material_id,content_hash) REFERENCES investment_lead_materials(material_id,content_hash) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_investment_observations_account ON investment_lead_observations(screen_name_lower,material_id,content_hash);
CREATE TABLE IF NOT EXISTS investment_lead_tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  material_id text NOT NULL,
  content_hash text NOT NULL,
  stage text NOT NULL CHECK(stage IN ('scan','derive','supplement')),
  prompt_version text NOT NULL,
  status text NOT NULL CHECK(status IN ('pending','processing','succeeded','no_candidate','needs_material','budget_paused','ignored','failed','expired')),
  attempts integer NOT NULL DEFAULT 0,
  lease_until timestamptz,
  next_attempt_at timestamptz,
  actual_model text,
  fallback_reason text,
  input_tokens integer NOT NULL DEFAULT 0,
  output_tokens integer NOT NULL DEFAULT 0,
  last_error text,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  completed_at timestamptz,
  UNIQUE(material_id,content_hash,stage,prompt_version),
  FOREIGN KEY(material_id,content_hash) REFERENCES investment_lead_materials(material_id,content_hash) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_investment_tasks_due ON investment_lead_tasks(stage,status,next_attempt_at,created_at);
CREATE INDEX IF NOT EXISTS idx_investment_tasks_expiry ON investment_lead_tasks(status,created_at,id);
CREATE TABLE IF NOT EXISTS investment_lead_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  material_id text NOT NULL,
  content_hash text NOT NULL,
  classification text NOT NULL CHECK(classification IN ('driver_candidate','composable','no_candidate','incomplete')),
  subject text NOT NULL DEFAULT '', action text NOT NULL DEFAULT '', change_object text NOT NULL DEFAULT '',
  event_time text NOT NULL DEFAULT '', impact_relations_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  summary text NOT NULL DEFAULT '', reason text NOT NULL DEFAULT '', actual_model text NOT NULL,
  prompt_version text NOT NULL, created_at timestamptz NOT NULL,
  UNIQUE(material_id,content_hash,prompt_version),
  FOREIGN KEY(material_id,content_hash) REFERENCES investment_lead_materials(material_id,content_hash) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_investment_events_recent ON investment_lead_events(created_at DESC,subject);
CREATE INDEX IF NOT EXISTS idx_investment_events_expiry ON investment_lead_events(created_at,id);
CREATE TABLE IF NOT EXISTS investment_leads (
  id text PRIMARY KEY, subject text NOT NULL, driver_logic text NOT NULL, conditions text NOT NULL DEFAULT '',
  assets_json jsonb NOT NULL DEFAULT '[]'::jsonb, source_claims_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  replay_json jsonb NOT NULL DEFAULT '{}'::jsonb, first_seen_at timestamptz NOT NULL,
  last_substantive_at timestamptz NOT NULL, revision integer NOT NULL DEFAULT 1,
  status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','unlocated')),
  created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_investment_leads_window ON investment_leads(last_substantive_at DESC,status);
CREATE TABLE IF NOT EXISTS investment_lead_replay_imports (
  run_id text NOT NULL, source_lead_id text NOT NULL, lead_id text NOT NULL REFERENCES investment_leads(id),
  imported_at timestamptz NOT NULL, PRIMARY KEY(run_id,source_lead_id)
);
CREATE TABLE IF NOT EXISTS investment_lead_revisions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id text NOT NULL REFERENCES investment_leads(id) ON DELETE CASCADE,
  revision integer NOT NULL, subject text NOT NULL, driver_logic text NOT NULL, conditions text NOT NULL DEFAULT '',
  assets_json jsonb NOT NULL DEFAULT '[]'::jsonb, source_claims_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  source_materials_json jsonb NOT NULL DEFAULT '[]'::jsonb, actual_model text NOT NULL,
  prompt_version text NOT NULL, created_at timestamptz NOT NULL, UNIQUE(lead_id,revision)
);
CREATE TABLE IF NOT EXISTS investment_lead_sources (
  lead_id text NOT NULL REFERENCES investment_leads(id) ON DELETE CASCADE,
  material_id text NOT NULL, content_hash text NOT NULL, role text NOT NULL, created_at timestamptz NOT NULL,
  PRIMARY KEY(lead_id,material_id,content_hash,role),
  FOREIGN KEY(material_id,content_hash) REFERENCES investment_lead_materials(material_id,content_hash)
);
CREATE INDEX IF NOT EXISTS idx_investment_sources_material ON investment_lead_sources(material_id,content_hash);
CREATE TABLE IF NOT EXISTS investment_lead_usage (
  usage_date date NOT NULL, kind text NOT NULL CHECK(kind IN ('scan','derive','search','supplement')),
  calls integer NOT NULL DEFAULT 0, input_tokens integer NOT NULL DEFAULT 0, output_tokens integer NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL, PRIMARY KEY(usage_date,kind)
);
CREATE TABLE IF NOT EXISTS investment_lead_identity_searches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id text NOT NULL REFERENCES investment_leads(id) ON DELETE CASCADE,
  asset_key text NOT NULL, asset_name text NOT NULL, context_json jsonb NOT NULL,
  status text NOT NULL CHECK(status IN ('pending','processing','succeeded','unresolved','budget_paused','ignored','failed','expired')),
  attempts integer NOT NULL DEFAULT 0, lease_until timestamptz, next_attempt_at timestamptz,
  result_json jsonb NOT NULL DEFAULT '{}'::jsonb, last_error text, created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL, completed_at timestamptz, UNIQUE(lead_id,asset_key)
);
CREATE INDEX IF NOT EXISTS idx_investment_identity_search_due ON investment_lead_identity_searches(status,next_attempt_at,created_at);
CREATE INDEX IF NOT EXISTS idx_investment_identity_search_expiry ON investment_lead_identity_searches(status,created_at,id);
CREATE TABLE IF NOT EXISTS investment_lead_scheduler_cursor (
  stage text PRIMARY KEY CHECK(stage IN ('scan','derive','identity_search')), account_lower text NOT NULL
);
"""


INVESTMENT_LEADS_PLAYBOOK_MIGRATION_SQL = """
ALTER TABLE investment_leads ADD COLUMN IF NOT EXISTS playbook_json jsonb NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE investment_lead_events ADD COLUMN IF NOT EXISTS playbook_trigger text NOT NULL DEFAULT '';
ALTER TABLE investment_lead_tasks DROP CONSTRAINT IF EXISTS investment_lead_tasks_stage_check;
ALTER TABLE investment_lead_tasks ADD CONSTRAINT investment_lead_tasks_stage_check
  CHECK(stage IN ('scan','derive','supplement','playbook'));
ALTER TABLE investment_lead_usage DROP CONSTRAINT IF EXISTS investment_lead_usage_kind_check;
ALTER TABLE investment_lead_usage ADD CONSTRAINT investment_lead_usage_kind_check
  CHECK(kind IN ('scan','derive','search','supplement','playbook'));
CREATE INDEX IF NOT EXISTS idx_investment_leads_playbook
  ON investment_leads(last_substantive_at DESC) WHERE playbook_json <> '{}'::jsonb;
"""


INVESTMENT_LEADS_PLAYBOOK_FEEDBACK_MIGRATION_SQL = """
ALTER TABLE investment_leads ADD COLUMN IF NOT EXISTS playbook_feedback text NOT NULL DEFAULT '';
ALTER TABLE investment_leads ADD COLUMN IF NOT EXISTS playbook_feedback_at timestamptz;
ALTER TABLE investment_lead_materials ADD COLUMN IF NOT EXISTS playbook_feedback text NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS idx_investment_leads_playbook_feedback
  ON investment_leads(playbook_feedback, last_substantive_at DESC) WHERE playbook_feedback <> '';
"""


def initialize_investment_leads_schema(
    *, schema: str = "hottopic", settings: PostgresSettings | None = None,
) -> tuple[int, ...]:
    migrations = (
        PostgresMigration(
            1,
            "investment_leads_initial",
            sha256(INVESTMENT_LEADS_SCHEMA_SQL.encode("utf-8")).hexdigest(),
            lambda connection: connection.execute(INVESTMENT_LEADS_SCHEMA_SQL),
        ),
        PostgresMigration(
            2,
            "investment_leads_playbook_v1",
            sha256(INVESTMENT_LEADS_PLAYBOOK_MIGRATION_SQL.encode("utf-8")).hexdigest(),
            lambda connection: connection.execute(INVESTMENT_LEADS_PLAYBOOK_MIGRATION_SQL),
        ),
        PostgresMigration(
            3,
            "investment_leads_playbook_feedback_v1",
            sha256(INVESTMENT_LEADS_PLAYBOOK_FEEDBACK_MIGRATION_SQL.encode("utf-8")).hexdigest(),
            lambda connection: connection.execute(INVESTMENT_LEADS_PLAYBOOK_FEEDBACK_MIGRATION_SQL),
        ),
    )
    with connect_postgres(schema=schema, application_name="odaily-investment-leads-migrate", settings=settings) as connection:
        return apply_schema_migrations(
            connection,
            schema=schema,
            component="investment_leads",
            migrations=migrations,
            settings=settings,
        )
