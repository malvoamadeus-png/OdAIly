SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS editor_plugin_local_sessions (
 token_hash text PRIMARY KEY,user_id text,email text NOT NULL,display_name text,
 expires_at timestamptz NOT NULL,created_at timestamptz NOT NULL,last_seen_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_editor_plugin_local_sessions_expires ON editor_plugin_local_sessions(expires_at);
CREATE TABLE IF NOT EXISTS editor_plugin_local_feed_items (
 feed_item_id text NOT NULL,feed_kind text NOT NULL,lane text NOT NULL,priority integer NOT NULL DEFAULT 0,
 title text NOT NULL DEFAULT '',summary text NOT NULL DEFAULT '',badges_json jsonb NOT NULL DEFAULT '[]',
 status_label text,status_tone text,occurred_at timestamptz NOT NULL,source_url text,detail_url text,
 action_schema_json jsonb NOT NULL DEFAULT '{}',meta_json jsonb NOT NULL DEFAULT '{}',
 created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL,PRIMARY KEY(feed_item_id,feed_kind)
);
CREATE INDEX IF NOT EXISTS idx_editor_plugin_local_feed_lane_time ON editor_plugin_local_feed_items(lane,occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_editor_plugin_local_feed_time ON editor_plugin_local_feed_items(occurred_at DESC);
CREATE TABLE IF NOT EXISTS editor_plugin_local_feedbacks (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,feed_item_id text NOT NULL,feed_kind text NOT NULL,
 feedback text NOT NULL CHECK(feedback IN ('accept','reject')),actor_user_id text,actor_email text NOT NULL,
 actor_display_name text,acted_at timestamptz NOT NULL,session_id text,extra_json jsonb NOT NULL DEFAULT '{}',
 sync_status text NOT NULL DEFAULT 'pending',sync_attempt_count integer NOT NULL DEFAULT 0,last_error text,
 created_at timestamptz NOT NULL,updated_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_editor_plugin_local_feedbacks_actor_feed ON editor_plugin_local_feedbacks(actor_email,feed_item_id,feed_kind,acted_at DESC,id DESC);
CREATE INDEX IF NOT EXISTS idx_editor_plugin_local_feedbacks_sync ON editor_plugin_local_feedbacks(sync_status,updated_at);
CREATE TABLE IF NOT EXISTS editor_plugin_local_reads (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,feed_item_id text NOT NULL,feed_kind text NOT NULL,delivery_key text,
 content_hash text NOT NULL,actor_user_id text,actor_email text NOT NULL,actor_display_name text,
 first_seen_at timestamptz NOT NULL,last_seen_at timestamptz NOT NULL,seen_count integer NOT NULL DEFAULT 1,
 read_method text NOT NULL CHECK(read_method IN ('alt_lens','title_expand')),
 UNIQUE(feed_item_id,feed_kind,actor_email,content_hash)
);
CREATE INDEX IF NOT EXISTS idx_editor_plugin_local_reads_delivery ON editor_plugin_local_reads(delivery_key,last_seen_at DESC);
"""
MANUAL_REJECTION_OUTBOX_SQL = """
ALTER TABLE editor_plugin_local_feedbacks ADD COLUMN IF NOT EXISTS manual_rejection_status text NOT NULL DEFAULT 'not_applicable';
ALTER TABLE editor_plugin_local_feedbacks ADD COLUMN IF NOT EXISTS manual_rejection_attempt_count integer NOT NULL DEFAULT 0;
ALTER TABLE editor_plugin_local_feedbacks ADD COLUMN IF NOT EXISTS manual_rejection_next_attempt_at timestamptz;
ALTER TABLE editor_plugin_local_feedbacks ADD COLUMN IF NOT EXISTS manual_rejection_last_error text;
CREATE INDEX IF NOT EXISTS idx_editor_plugin_local_manual_rejections ON editor_plugin_local_feedbacks(manual_rejection_status,manual_rejection_next_attempt_at,id);
UPDATE editor_plugin_local_feedbacks SET manual_rejection_status='pending',manual_rejection_next_attempt_at=created_at WHERE manual_rejection_status='not_applicable' AND feed_kind='auditor_alert' AND feedback='reject' AND feed_item_id ~ '^auditor:[1-9][0-9]*$'
"""


def _now() -> datetime:
    return datetime.now(UTC)


def _dt(value: Any) -> datetime:
    parsed = value if isinstance(value, datetime) else datetime.fromisoformat(str(value).replace('Z', '+00:00'))
    return parsed.replace(tzinfo=UTC) if parsed.tzinfo is None else parsed.astimezone(UTC)


def _json(value: Any, fallback: Any) -> Any:
    if value is None:
        return fallback
    if isinstance(value, (dict, list)):
        return value
    try:
        return json.loads(value)
    except (TypeError, ValueError):
        return fallback


class PostgresEditorPluginLocalStore:
    def __init__(self, path=None, *, initialize: bool = True) -> None:
        self.path = path or 'postgres:main/editor_plugin_local'
        if initialize:
            self.initialize_schema()

    @staticmethod
    def initialize_schema() -> None:
        import hashlib
        with connect_postgres(schema='main', application_name='odaily-editor-local-migrate') as conn:
            apply_schema_migrations(conn, schema='main', component='editor_plugin_local', migrations=(
                PostgresMigration(1, 'editor plugin local store', hashlib.sha256(SCHEMA_SQL.encode()).hexdigest(),
                                  lambda connection: connection.execute(SCHEMA_SQL)),
                PostgresMigration(2, 'editor plugin manual rejection outbox', hashlib.sha256(MANUAL_REJECTION_OUTBOX_SQL.encode()).hexdigest(),
                                  lambda connection: [connection.execute(statement) for statement in MANUAL_REJECTION_OUTBOX_SQL.split(';') if statement.strip()]),
            ))

    def upsert_session(self, *, token_hash: str, user_id: str | None, email: str, display_name: str | None, expires_at: datetime) -> None:
        now = _now()
        with connect_postgres(schema='main', application_name='odaily-editor-local-session') as conn:
            conn.execute('DELETE FROM editor_plugin_local_sessions WHERE expires_at<=%s', (now,))
            conn.execute('INSERT INTO editor_plugin_local_sessions(token_hash,user_id,email,display_name,expires_at,created_at,last_seen_at) VALUES(%s,%s,%s,%s,%s,%s,%s) ON CONFLICT(token_hash) DO UPDATE SET user_id=excluded.user_id,email=excluded.email,display_name=excluded.display_name,expires_at=excluded.expires_at,last_seen_at=excluded.last_seen_at',
                         (token_hash,user_id,email.strip().lower(),display_name,_dt(expires_at),now,now))

    def get_session(self, token_hash: str) -> LocalPluginSession | None:
        now = _now()
        with connect_postgres(schema='main', application_name='odaily-editor-local-session') as conn:
            row = conn.execute('UPDATE editor_plugin_local_sessions SET last_seen_at=%s WHERE token_hash=%s AND expires_at>%s RETURNING *',(now,token_hash,now)).fetchone()
        return LocalPluginSession(token_hash=row['token_hash'],user_id=row['user_id'],email=row['email'],display_name=row['display_name'],expires_at=row['expires_at'],created_at=row['created_at'],last_seen_at=row['last_seen_at']) if row else None

    def delete_session(self, token_hash: str) -> None:
        with connect_postgres(schema='main', application_name='odaily-editor-local-session') as conn:
            conn.execute('DELETE FROM editor_plugin_local_sessions WHERE token_hash=%s',(token_hash,))

    def upsert_feed_items(self, rows: list[dict[str, Any]]) -> int:
        now=_now(); count=0
        with connect_postgres(schema='main', application_name='odaily-editor-local-feed') as conn:
            for row in rows:
                item_id=str(row.get('feed_item_id') or '').strip(); kind=str(row.get('feed_kind') or '').strip()
                if not item_id or not kind: continue
                conn.execute('INSERT INTO editor_plugin_local_feed_items(feed_item_id,feed_kind,lane,priority,title,summary,badges_json,status_label,status_tone,occurred_at,source_url,detail_url,action_schema_json,meta_json,created_at,updated_at) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT(feed_item_id,feed_kind) DO UPDATE SET lane=excluded.lane,priority=excluded.priority,title=excluded.title,summary=excluded.summary,badges_json=excluded.badges_json,status_label=excluded.status_label,status_tone=excluded.status_tone,occurred_at=excluded.occurred_at,source_url=excluded.source_url,detail_url=excluded.detail_url,action_schema_json=excluded.action_schema_json,meta_json=excluded.meta_json,updated_at=excluded.updated_at',
                    (item_id,kind,normalize_feed_lane(kind,str(row.get('lane') or 'high')),int(row.get('priority') or 0),str(row.get('title') or ''),str(row.get('summary') or ''),json.dumps(row.get('badges') or [],ensure_ascii=False),row.get('status_label'),row.get('status_tone'),_dt(row.get('occurred_at') or now),row.get('source_url'),row.get('detail_url'),json.dumps(row.get('action_schema') or {'type':'read'},ensure_ascii=False),json.dumps(row.get('meta_json') or {},ensure_ascii=False),now,now)); count+=1
        return count

    @staticmethod
    def _feed_payload(row) -> dict[str, Any]:
        return {'feed_item_id':row['feed_item_id'],'feed_kind':row['feed_kind'],'lane':normalize_feed_lane(row['feed_kind'],row['lane']),'priority':row['priority'],'title':row['title'],'summary':row['summary'],'badges':_json(row['badges_json'],[]),'status_label':row['status_label'],'status_tone':row['status_tone'],'occurred_at':row['occurred_at'].isoformat(),'source_url':row['source_url'],'detail_url':row['detail_url'],'action_schema':_json(row['action_schema_json'],{'type':'read'}),'meta_json':_json(row['meta_json'],{})}

    def list_feed_items(self, *, limit: int, max_age_hours: int) -> list[dict[str, Any]]:
        cutoff=_now()-timedelta(hours=max_age_hours); safe_limit=max(1,min(int(limit or 120),500))
        with connect_postgres(schema='main', application_name='odaily-editor-local-feed') as conn:
            rows=conn.execute("SELECT * FROM editor_plugin_local_feed_items WHERE occurred_at>=%s ORDER BY CASE WHEN feed_kind IN ('whale_onchain','whale_hyperliquid') THEN 1 WHEN lane='high' THEN 1 WHEN lane='ai' THEN 2 WHEN lane='low' THEN 3 ELSE 4 END,occurred_at DESC,updated_at DESC LIMIT %s",(cutoff,safe_limit)).fetchall()
        return [self._feed_payload(row) for row in rows]

    def feed_state(self, *, actor_email: str, feed_item_ids: list[str]) -> list[dict[str, Any]]:
        ids=[str(item).strip() for item in feed_item_ids if str(item).strip()]
        if not ids:return []
        with connect_postgres(schema='main', application_name='odaily-editor-local-state') as conn:
            rows=conn.execute("SELECT DISTINCT ON(feed_item_id,feed_kind) feed_item_id,feed_kind,feedback,acted_at FROM editor_plugin_local_feedbacks WHERE lower(actor_email)=lower(%s) AND feed_item_id=ANY(%s) ORDER BY feed_item_id,feed_kind,acted_at DESC,id DESC",(actor_email.strip().lower(),ids)).fetchall()
            current=conn.execute('SELECT feed_item_id,feed_kind,title,summary FROM editor_plugin_local_feed_items WHERE feed_item_id=ANY(%s)',(ids,)).fetchall()
            reads=conn.execute('SELECT feed_item_id,feed_kind,content_hash,first_seen_at,last_seen_at,seen_count,read_method FROM editor_plugin_local_reads WHERE lower(actor_email)=lower(%s) AND feed_item_id=ANY(%s) ORDER BY last_seen_at DESC,id DESC',(actor_email.strip().lower(),ids)).fetchall()
        state={(r['feed_item_id'],r['feed_kind']):{'feed_item_id':r['feed_item_id'],'feed_kind':r['feed_kind'],'latest_feedback':r['feedback'],'latest_feedback_at':r['acted_at'].isoformat()} for r in rows}
        hashes={(r['feed_item_id'],r['feed_kind']):hashlib.sha256(f"{r['title']}\n{r['summary']}".encode()).hexdigest() for r in current}
        for r in reads:
            key=(r['feed_item_id'],r['feed_kind'])
            if hashes.get(key)!=r['content_hash']:continue
            entry=state.setdefault(key,{'feed_item_id':key[0],'feed_kind':key[1]})
            if 'is_read' not in entry:entry.update({'is_read':True,'first_seen_at':r['first_seen_at'].isoformat(),'last_seen_at':r['last_seen_at'].isoformat(),'seen_count':r['seen_count'],'read_method':r['read_method']})
        return list(state.values())

    def mark_seen(self, *, feed_item_id: str, feed_kind: str, read_method: str, actor_user_id: str | None, actor_email: str, actor_display_name: str | None) -> dict[str, Any]:
        if not feed_item_id.strip():raise ValueError('editor_plugin_feed_item_id_required')
        if not feed_kind.strip():raise ValueError('editor_plugin_feed_kind_required')
        if read_method not in {'alt_lens','title_expand'}:raise ValueError('editor_plugin_invalid_read_method')
        actor=actor_email.strip().lower()
        if not actor:raise ValueError('editor_plugin_actor_email_required')
        now=_now(); item_id=feed_item_id.strip(); kind=feed_kind.strip()
        with connect_postgres(schema='main', application_name='odaily-editor-local-seen') as conn:
            with conn.transaction():
                item=conn.execute('SELECT title,summary,meta_json FROM editor_plugin_local_feed_items WHERE feed_item_id=%s AND feed_kind=%s',(item_id,kind)).fetchone()
                if item is None:raise ValueError('editor_plugin_feed_item_not_found')
                if not str(item['summary'] or '').strip():return {'ok':True,'recorded':False,'local':True}
                digest=hashlib.sha256(f"{item['title']}\n{item['summary']}".encode()).hexdigest(); meta=_json(item['meta_json'],{})
                delivery=str(meta.get('odaily_delivery_key') or '').strip() if isinstance(meta,dict) else ''
                conn.execute('INSERT INTO editor_plugin_local_reads(feed_item_id,feed_kind,delivery_key,content_hash,actor_user_id,actor_email,actor_display_name,first_seen_at,last_seen_at,seen_count,read_method) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,1,%s) ON CONFLICT(feed_item_id,feed_kind,actor_email,content_hash) DO UPDATE SET delivery_key=excluded.delivery_key,actor_user_id=excluded.actor_user_id,actor_display_name=excluded.actor_display_name,last_seen_at=excluded.last_seen_at,seen_count=editor_plugin_local_reads.seen_count+1,read_method=excluded.read_method',(item_id,kind,delivery or None,digest,actor_user_id,actor,actor_display_name,now,now,read_method))
        return {'ok':True,'recorded':True,'local':True,'first_seen_at':now.isoformat()}

    def readers_for_delivery_keys(self, delivery_keys: list[str]) -> dict[str,list[dict[str,Any]]]:
        keys=[str(k).strip() for k in delivery_keys if str(k).strip()]
        if not keys:return {}
        with connect_postgres(schema='main', application_name='odaily-editor-local-readers') as conn:rows=conn.execute('SELECT delivery_key,content_hash,actor_user_id,actor_email,actor_display_name,first_seen_at,last_seen_at,seen_count,read_method FROM editor_plugin_local_reads WHERE delivery_key=ANY(%s) ORDER BY delivery_key,last_seen_at DESC,id DESC',(keys,)).fetchall()
        out={}
        for r in rows:out.setdefault(r['delivery_key'],[]).append({'content_hash':r['content_hash'],'actor_user_id':r['actor_user_id'],'actor_email':r['actor_email'],'actor_display_name':r['actor_display_name'],'first_seen_at':r['first_seen_at'].isoformat(),'last_seen_at':r['last_seen_at'].isoformat(),'seen_count':r['seen_count'],'read_method':r['read_method']})
        return out

    def record_feedback(self, *, feed_item_id: str, feed_kind: str, feedback: str, actor_user_id: str | None, actor_email: str, actor_display_name: str | None, session_id: str | None, extra_json: dict[str,Any]) -> dict[str,Any]:
        item_id=feed_item_id.strip(); kind=feed_kind.strip(); vote=feedback.strip()
        if not item_id:raise ValueError('editor_plugin_feed_item_id_required')
        if vote not in {'accept','reject'}:raise ValueError('editor_plugin_invalid_feedback')
        manual_status='not_applicable'
        if kind=='auditor_alert' and vote=='reject' and item_id.startswith('auditor:'):
            try:
                if int(item_id.split(':',1)[1])>0:manual_status='pending'
            except ValueError:pass
        now=_now()
        with connect_postgres(schema='main', application_name='odaily-editor-local-feedback') as conn:
            row=conn.execute("INSERT INTO editor_plugin_local_feedbacks(feed_item_id,feed_kind,feedback,actor_user_id,actor_email,actor_display_name,acted_at,session_id,extra_json,sync_status,manual_rejection_status,manual_rejection_next_attempt_at,created_at,updated_at) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,'pending',%s,CASE WHEN %s='pending' THEN %s END,%s,%s) RETURNING id",(item_id,kind,vote,actor_user_id,actor_email.strip().lower(),actor_display_name,now,session_id,json.dumps(extra_json,ensure_ascii=False),manual_status,manual_status,now,now,now)).fetchone()
        return {'ok':True,'local':True,'queued':True,'feedback_id':row['id']}

    def pending_manual_rejections(self, *, limit: int = 100) -> list[PendingManualRejection]:
        with connect_postgres(schema='main', application_name='odaily-editor-manual-rejection-outbox') as conn:
            rows=conn.execute("SELECT id,feed_item_id,actor_email,manual_rejection_status FROM editor_plugin_local_feedbacks WHERE manual_rejection_status IN ('pending','queued') AND (manual_rejection_status='queued' OR manual_rejection_next_attempt_at IS NULL OR manual_rejection_next_attempt_at<=clock_timestamp()) ORDER BY id LIMIT %s",(max(1,min(int(limit),500)),)).fetchall()
        result=[]
        for row in rows:
            try:audit_id=int(str(row['feed_item_id']).split(':',1)[1])
            except (IndexError,ValueError):continue
            result.append(PendingManualRejection(int(row['id']),audit_id,str(row['actor_email']),str(row['manual_rejection_status'])))
        return result

    def mark_manual_rejection_queued(self, feedback_id: int) -> None:
        with connect_postgres(schema='main', application_name='odaily-editor-manual-rejection-outbox') as conn:
            conn.execute("UPDATE editor_plugin_local_feedbacks SET manual_rejection_status='queued',manual_rejection_last_error=NULL,manual_rejection_next_attempt_at=NULL,updated_at=clock_timestamp() WHERE id=%s AND manual_rejection_status='pending'",(feedback_id,))

    def mark_manual_rejection_complete(self, feedback_id: int, *, deleted: bool = False) -> None:
        status='deleted' if deleted else 'completed'
        with connect_postgres(schema='main', application_name='odaily-editor-manual-rejection-outbox') as conn:
            conn.execute("UPDATE editor_plugin_local_feedbacks SET manual_rejection_status=%s,manual_rejection_last_error=NULL,manual_rejection_next_attempt_at=NULL,updated_at=clock_timestamp() WHERE id=%s AND manual_rejection_status='queued'",(status,feedback_id))

    def mark_manual_rejection_failed(self, feedback_id: int, *, error: str) -> None:
        now=_now()
        with connect_postgres(schema='main', application_name='odaily-editor-manual-rejection-outbox') as conn:
            row=conn.execute("UPDATE editor_plugin_local_feedbacks SET manual_rejection_status='pending',manual_rejection_attempt_count=manual_rejection_attempt_count+1,manual_rejection_last_error=%s,manual_rejection_next_attempt_at=clock_timestamp()+(LEAST(21600,30*power(2,LEAST(manual_rejection_attempt_count,10))) * interval '1 second'),updated_at=%s WHERE id=%s RETURNING id",(error[:2000],now,feedback_id)).fetchone()

    def list_pending_feedbacks(self, *, limit: int = 50) -> list[PendingPluginFeedback]:
        with connect_postgres(schema='main', application_name='odaily-editor-local-feedback') as conn:rows=conn.execute("SELECT id,feed_item_id,feed_kind,feedback,actor_email,session_id,extra_json FROM editor_plugin_local_feedbacks WHERE sync_status IN ('pending','failed') ORDER BY created_at,id LIMIT %s",(max(1,min(limit,200)),)).fetchall()
        return [PendingPluginFeedback(id=r['id'],feed_item_id=r['feed_item_id'],feed_kind=r['feed_kind'],feedback=r['feedback'],actor_email=r['actor_email'],session_id=r['session_id'],extra_json=_json(r['extra_json'],{})) for r in rows]

    def mark_feedback_synced(self, feedback_id: int) -> None:
        with connect_postgres(schema='main', application_name='odaily-editor-local-feedback') as conn:conn.execute("UPDATE editor_plugin_local_feedbacks SET sync_status='synced',last_error=NULL,updated_at=%s WHERE id=%s",(_now(),feedback_id))

    def mark_feedback_failed(self, feedback_id: int, *, error: str) -> None:
        with connect_postgres(schema='main', application_name='odaily-editor-local-feedback') as conn:conn.execute("UPDATE editor_plugin_local_feedbacks SET sync_status='failed',sync_attempt_count=sync_attempt_count+1,last_error=%s,updated_at=%s WHERE id=%s",(error[:2000],_now(),feedback_id))

    def prune_old(self, *, feed_retention_hours: int = 24, synced_feedback_retention_days: int = 90) -> None:
        now=_now()
        with connect_postgres(schema='main', application_name='odaily-editor-local-prune') as conn:
            with conn.transaction():
                conn.execute('DELETE FROM editor_plugin_local_feed_items WHERE occurred_at<%s',(now-timedelta(hours=feed_retention_hours),))
                conn.execute("DELETE FROM editor_plugin_local_feedbacks WHERE sync_status='synced' AND created_at<%s AND manual_rejection_status NOT IN ('pending','queued')",(now-timedelta(days=synced_feedback_retention_days),))
                conn.execute('DELETE FROM editor_plugin_local_sessions WHERE expires_at<=%s',(now,))

    def stats(self, *, max_age_hours: int = 2) -> dict[str,Any]:
        cutoff=_now()-timedelta(hours=max_age_hours)
        with connect_postgres(schema='main', application_name='odaily-editor-local-stats') as conn:
            total=conn.execute('SELECT count(*) n FROM editor_plugin_local_feed_items').fetchone()['n']; recent=conn.execute('SELECT count(*) n FROM editor_plugin_local_feed_items WHERE occurred_at>=%s',(cutoff,)).fetchone()['n']; latest=conn.execute('SELECT max(occurred_at) t FROM editor_plugin_local_feed_items').fetchone()['t']; lanes=conn.execute('SELECT lane,count(*) n FROM editor_plugin_local_feed_items WHERE occurred_at>=%s GROUP BY lane ORDER BY lane',(cutoff,)).fetchall(); kinds=conn.execute('SELECT feed_kind,count(*) n FROM editor_plugin_local_feed_items WHERE occurred_at>=%s GROUP BY feed_kind ORDER BY feed_kind',(cutoff,)).fetchall(); statuses=conn.execute('SELECT sync_status,count(*) n FROM editor_plugin_local_feedbacks GROUP BY sync_status ORDER BY sync_status').fetchall(); sessions=conn.execute('SELECT count(*) n FROM editor_plugin_local_sessions WHERE expires_at>%s',(_now(),)).fetchone()['n']
        by_status={r['sync_status']:r['n'] for r in statuses}
        return {'path':str(self.path),'max_age_hours':max_age_hours,'feed_items':{'total':total,'recent':recent,'latest_occurred_at':latest.isoformat() if latest else None,'by_lane':{r['lane']:r['n'] for r in lanes},'by_kind':{r['feed_kind']:r['n'] for r in kinds}},'feedbacks':{'by_sync_status':by_status,'pending':by_status.get('pending',0),'failed':by_status.get('failed',0)},'sessions':{'active':sessions}}
