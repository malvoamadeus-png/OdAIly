def initialize_hottopic_schema(*, schema: str = "hottopic", settings: PostgresSettings | None = None) -> tuple[int, ...]:
    migration = PostgresMigration(
        1,
        "hottopic_core_and_aggregator",
        sha256(HOT_TOPIC_POSTGRES_SCHEMA_SQL.encode("utf-8")).hexdigest(),
        lambda connection: connection.execute(HOT_TOPIC_POSTGRES_SCHEMA_SQL),
    )
    with connect_postgres(schema=schema, application_name="odaily-hottopic-migrate", settings=settings) as connection:
        lease_sql = """CREATE TABLE IF NOT EXISTS event_tracking_work_leases (
          work_key text PRIMARY KEY, claim_token text NOT NULL, claimed_at timestamptz NOT NULL,
          lease_until timestamptz NOT NULL, attempts integer NOT NULL DEFAULT 1
        ); CREATE INDEX IF NOT EXISTS idx_event_tracking_work_leases_expiry ON event_tracking_work_leases(lease_until);"""
        lease_migration = PostgresMigration(
            2, "event_tracking_fenced_work_leases",
            sha256(lease_sql.encode("utf-8")).hexdigest(), lambda conn: conn.execute(lease_sql),
        )
        versions = apply_schema_migrations(
            connection, schema=schema, component="hottopic", migrations=(migration, lease_migration), settings=settings,
        )
        return versions


def datetime_now_iso() -> str:
    from datetime import UTC, datetime

    return datetime.now(UTC).isoformat()
