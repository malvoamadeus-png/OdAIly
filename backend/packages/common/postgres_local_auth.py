from __future__ import annotations

import hashlib
import os
import secrets
from datetime import UTC, datetime, timedelta
from hashlib import sha256

from packages.common.pg_native import PostgresMigration, apply_schema_migrations, connect_postgres, postgres_transaction

from .local_auth import (
    DEFAULT_LOCAL_OPERATOR_EMAIL,
    DEFAULT_LOCAL_OPERATOR_PASSWORD_HASH,
    LocalAuthSession,
    LocalOperator,
    _now,
    hash_password,
    hash_session_token,
    verify_password,
)

SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS local_auth_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL,
    password_hash text NOT NULL,
    display_name text NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_local_auth_users_email_lower ON local_auth_users(lower(email));
CREATE TABLE IF NOT EXISTS local_auth_sessions (
    token_hash text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES local_auth_users(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_local_auth_sessions_expires ON local_auth_sessions(expires_at);
"""
SCHEMA_CHECKSUM = sha256(SCHEMA_SQL.encode("utf-8")).hexdigest()


class PostgresLocalAuthRepository:
    def __init__(self) -> None:
        self.init_schema()

    def _connect(self):
        return connect_postgres(schema="main", application_name="odaily-local-auth")

    @staticmethod
    def initialize_schema() -> None:
        with connect_postgres(schema="main", application_name="odaily-local-auth-migrate") as connection:
            apply_schema_migrations(
                connection,
                schema="main",
                component="local_auth",
                migrations=(PostgresMigration(
                    1, "local_auth_initial", SCHEMA_CHECKSUM,
                    lambda conn: conn.execute(SCHEMA_SQL),
                ),),
            )
    def init_schema(self) -> None:
        self.initialize_schema()
        with self._connect() as connection:
            email = (os.getenv("ODAILY_LOCAL_AUTH_EMAIL") or DEFAULT_LOCAL_OPERATOR_EMAIL).strip().lower()
            password_hash = os.getenv("ODAILY_LOCAL_AUTH_PASSWORD_HASH") or DEFAULT_LOCAL_OPERATOR_PASSWORD_HASH
            with postgres_transaction(connection):
                connection.execute(
                    "INSERT INTO local_auth_users(email,password_hash,display_name,enabled) "
                    "VALUES(%s,%s,%s,true) ON CONFLICT(lower(email)) DO NOTHING",
                    (email, password_hash, email.split("@", 1)[0]),
                )

    def login(self, email: str, password: str, *, ttl_hours: float = 720.0) -> tuple[str, LocalAuthSession]:
        normalized = email.strip().lower()
        now = _now()
        with self._connect() as connection:
            row = connection.execute(
                "SELECT id,email,password_hash,display_name FROM local_auth_users "
                "WHERE lower(email)=%s AND enabled=true",
                (normalized,),
            ).fetchone()
            if row is None or not verify_password(password, str(row["password_hash"])):
                raise ValueError("Invalid email or password")
            with postgres_transaction(connection):
                current = connection.execute(
                    "SELECT password_hash,enabled FROM local_auth_users WHERE id=%s FOR UPDATE",
                    (row["id"],),
                ).fetchone()
                if current is None or not current["enabled"] or current["password_hash"] != row["password_hash"]:
                    raise ValueError("Invalid email or password")
                token = secrets.token_urlsafe(32)
                expires_at = now + timedelta(hours=ttl_hours)
                connection.execute("DELETE FROM local_auth_sessions WHERE expires_at<=%s", (now,))
                connection.execute(
                    "INSERT INTO local_auth_sessions(token_hash,user_id,expires_at) VALUES(%s,%s,%s)",
                    (hash_session_token(token), row["id"], expires_at),
                )
        operator = LocalOperator(id=int(row["id"]), email=str(row["email"]), display_name=str(row["display_name"]))
        return token, LocalAuthSession(operator=operator, expires_at=expires_at)

    def authenticate(self, token: str) -> LocalAuthSession | None:
        now = _now()
        token_hash = hash_session_token(token)
        with self._connect() as connection:
            with postgres_transaction(connection):
                row = connection.execute(
                    "SELECT u.id,u.email,u.display_name,s.expires_at FROM local_auth_sessions s "
                    "JOIN local_auth_users u ON u.id=s.user_id "
                    "WHERE s.token_hash=%s AND s.expires_at>%s AND u.enabled=true",
                    (token_hash, now),
                ).fetchone()
                if row is None:
                    return None
                connection.execute("UPDATE local_auth_sessions SET last_seen_at=%s WHERE token_hash=%s", (now, token_hash))
        operator = LocalOperator(id=int(row["id"]), email=str(row["email"]), display_name=str(row["display_name"]))
        return LocalAuthSession(operator=operator, expires_at=row["expires_at"])

    def logout(self, token: str) -> None:
        with self._connect() as connection:
            connection.execute("DELETE FROM local_auth_sessions WHERE token_hash=%s", (hash_session_token(token),))

    def set_password(self, email: str, password: str) -> None:
        normalized = email.strip().lower()
        password_hash = hash_password(password)
        with self._connect() as connection:
            with postgres_transaction(connection):
                row = connection.execute(
                    "SELECT id FROM local_auth_users WHERE lower(email)=%s FOR UPDATE",
                    (normalized,),
                ).fetchone()
                if row is None:
                    raise ValueError("local operator not found")
                result = connection.execute(
                    "UPDATE local_auth_users SET password_hash=%s,updated_at=now() WHERE lower(email)=%s",
                    (password_hash, normalized),
                )
                if result.rowcount != 1:
                    raise ValueError("local operator not found")
                connection.execute(
                    "DELETE FROM local_auth_sessions WHERE user_id=(SELECT id FROM local_auth_users WHERE lower(email)=%s)",
                    (normalized,),
                )
