from __future__ import annotations

import json
from contextlib import contextmanager
from datetime import UTC, datetime
from hashlib import sha256
from typing import Any

from packages.common.pg_native import PostgresMigration, apply_schema_migrations, connect_postgres, postgres_transaction
from packages.common.storage import load_storage_settings

from .editor_plugin_auth import (
    DEFAULT_LOCAL_OPERATOR_EMAIL,
    EditorPluginGenerationLogInput,
    EditorPluginSessionRecord,
    EditorPluginUserRecord,
    normalize_editor_plugin_display_name,
    normalize_editor_plugin_email,
)
from .local_auth import create_local_auth_repository

SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS editor_plugin_users (
    email text PRIMARY KEY,
    display_name text,
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS editor_plugin_generation_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action text NOT NULL,
    actor_user_id text,
    actor_email text NOT NULL,
    actor_display_name text,
    source_type text NOT NULL,
    platform text NOT NULL,
    post_id text,
    post_url text,
    author_display_name text,
    author_handle text,
    posted_at timestamptz,
    request_text text NOT NULL,
    route text,
    result_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text NOT NULL,
    error_message text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_editor_plugin_generation_logs_actor_created
    ON editor_plugin_generation_logs(actor_email,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_editor_plugin_generation_logs_action_created
    ON editor_plugin_generation_logs(action,created_at DESC);
"""
SCHEMA_CHECKSUM = sha256(SCHEMA_SQL.encode("utf-8")).hexdigest()


class PostgresEditorPluginAuthRepository:
    PLUGIN_FUNCTIONS = frozenset({
        "editor_plugin_profile", "editor_plugin_feed", "editor_plugin_state",
        "editor_plugin_mark_seen", "editor_plugin_submit_feedback",
    })

    def __init__(self) -> None:
        self.local_auth = create_local_auth_repository()
        self.init_schema()

    @contextmanager
    def _connect(self):
        with connect_postgres(schema="main", application_name="odaily-editor-plugin-auth") as connection:
            with postgres_transaction(connection):
                yield connection

    def init_schema(self) -> None:
        self.initialize_schema()
        email = normalize_editor_plugin_email(DEFAULT_LOCAL_OPERATOR_EMAIL)
        with connect_postgres(schema="main", application_name="odaily-editor-plugin-auth-seed") as connection:
            with postgres_transaction(connection):
                connection.execute(
                    "INSERT INTO editor_plugin_users(email,display_name,enabled) VALUES(%s,%s,true) "
                    "ON CONFLICT(email) DO NOTHING",
                    (email, email.split("@", 1)[0]),
                )

    @staticmethod
    def initialize_schema() -> None:
        with connect_postgres(schema="main", application_name="odaily-editor-plugin-auth-migrate") as connection:
            apply_schema_migrations(
                connection,
                schema="main",
                component="editor_plugin_auth",
                migrations=(PostgresMigration(
                    1, "editor_plugin_auth_initial", SCHEMA_CHECKSUM,
                    lambda conn: conn.execute(SCHEMA_SQL),
                ), PostgresMigration(
                    2, "editor_plugin_external_error_counter", sha256(b"ALTER TABLE editor_plugin_generation_logs ADD COLUMN IF NOT EXISTS odaily_external_error_counted integer NOT NULL DEFAULT 0").hexdigest(),
                    lambda conn: conn.execute("ALTER TABLE editor_plugin_generation_logs ADD COLUMN IF NOT EXISTS odaily_external_error_counted integer NOT NULL DEFAULT 0"),
                )),
            )
    @staticmethod
    def _user(row) -> EditorPluginUserRecord:
        return EditorPluginUserRecord(
            email=str(row["email"]), display_name=row["display_name"], enabled=bool(row["enabled"]),
            created_at=row["created_at"].isoformat(), updated_at=row["updated_at"].isoformat(),
        )

    def upsert_user(self, email: str, display_name: str | None = None, *, enabled: bool = True) -> EditorPluginUserRecord:
        email = normalize_editor_plugin_email(email)
        with self._connect() as connection:
            row = connection.execute(
                "INSERT INTO editor_plugin_users(email,display_name,enabled) VALUES(%s,%s,%s) "
                "ON CONFLICT(email) DO UPDATE SET display_name=coalesce(excluded.display_name,editor_plugin_users.display_name), "
                "enabled=excluded.enabled,updated_at=now() RETURNING *",
                (email, normalize_editor_plugin_display_name(display_name), enabled),
            ).fetchone()
        return self._user(row)

    def delete_user(self, email: str) -> bool:
        with self._connect() as connection:
            result = connection.execute("DELETE FROM editor_plugin_users WHERE lower(email)=lower(%s)", (normalize_editor_plugin_email(email),))
            return bool(result.rowcount)

    def list_users(self) -> list[EditorPluginUserRecord]:
        with self._connect() as connection:
            rows = connection.execute("SELECT * FROM editor_plugin_users ORDER BY enabled DESC,email").fetchall()
        return [self._user(row) for row in rows]

    def get_enabled_user(self, email: str) -> EditorPluginUserRecord | None:
        with self._connect() as connection:
            row = connection.execute("SELECT * FROM editor_plugin_users WHERE lower(email)=lower(%s) AND enabled=true", (normalize_editor_plugin_email(email),)).fetchone()
        return self._user(row) if row else None

    def verify_local_password(self, email: str, password: str) -> tuple[str | None, str]:
        token, session = self.local_auth.login(email, password, ttl_hours=1 / 60)
        self.local_auth.logout(token)
        return str(session.operator.id), session.operator.email

    def create_session(self, *, token_hash: str, user_id: str | None, email: str, display_name: str | None, expires_at: datetime) -> None:
        return None

    def get_session(self, token_hash: str) -> EditorPluginSessionRecord | None:
        return None

    def delete_session(self, token_hash: str) -> None:
        return None

    def call_plugin_function(self, *, email: str, function_name: str, args: tuple[Any, ...] = ()) -> list[dict[str, Any]]:
        return []

    def call_plugin_json_function(self, *, email: str, function_name: str, args: tuple[Any, ...]) -> Any:
        return None

    def insert_generation_log(self, payload: EditorPluginGenerationLogInput) -> None:
        with self._connect() as connection:
            connection.execute(
                """INSERT INTO editor_plugin_generation_logs(
                    action,actor_user_id,actor_email,actor_display_name,source_type,platform,post_id,post_url,
                    author_display_name,author_handle,posted_at,request_text,route,result_json,status,error_message
                ) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
                (payload.action, payload.actor_user_id, normalize_editor_plugin_email(payload.actor_email),
                 normalize_editor_plugin_display_name(payload.actor_display_name), payload.source_type, payload.platform,
                 payload.post_id, payload.post_url, payload.author_display_name, payload.author_handle, payload.posted_at,
                 payload.request_text, payload.route, json.dumps(payload.result_json, ensure_ascii=False), payload.status,
                 payload.error_message),
            )
