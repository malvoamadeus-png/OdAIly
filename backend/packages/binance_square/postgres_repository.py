SCHEMA_SQL = f"""
CREATE TABLE IF NOT EXISTS binance_square_settings(singleton_key text PRIMARY KEY CHECK(singleton_key='global'),enabled boolean NOT NULL DEFAULT false,interval_seconds integer NOT NULL DEFAULT {POLL_INTERVAL_SECONDS},worker_status text NOT NULL DEFAULT 'stopped',worker_last_seen_at timestamptz,updated_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS binance_square_accounts(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,slug text NOT NULL,slug_lower text NOT NULL UNIQUE,profile_url text NOT NULL,square_uid text,display_name text,write_name text,enabled boolean NOT NULL DEFAULT true,seeded_at timestamptz,last_polled_at timestamptz,last_success_at timestamptz,last_error text,created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now());
CREATE INDEX IF NOT EXISTS idx_binance_square_accounts_enabled ON binance_square_accounts(enabled);
CREATE TABLE IF NOT EXISTS binance_square_seen_posts(post_id text PRIMARY KEY,account_id bigint REFERENCES binance_square_accounts(id) ON DELETE SET NULL,seeded boolean NOT NULL DEFAULT false,created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS binance_square_attempts(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,account_id bigint REFERENCES binance_square_accounts(id) ON DELETE SET NULL,slug_lower text NOT NULL,status text NOT NULL,candidate_count integer NOT NULL DEFAULT 0,seeded_count integer NOT NULL DEFAULT 0,new_count integer NOT NULL DEFAULT 0,saved_count integer NOT NULL DEFAULT 0,error text,metadata jsonb NOT NULL DEFAULT '{{}}',started_at timestamptz NOT NULL,finished_at timestamptz NOT NULL,odaily_external_error_counted integer NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS idx_binance_square_attempts_started ON binance_square_attempts(started_at DESC);
"""


def _dt(value):
    if not value: return None
    return value if isinstance(value, datetime) else datetime.fromisoformat(str(value).replace('Z','+00:00'))


def _account(row):
    return BinanceSquareAccount(id=int(row['id']),slug=row['slug'],slug_lower=row['slug_lower'],profile_url=row['profile_url'],square_uid=row['square_uid'],display_name=row['display_name'],write_name=row['write_name'],enabled=bool(row['enabled']),seeded_at=_dt(row['seeded_at']),last_polled_at=_dt(row['last_polled_at']),last_success_at=_dt(row['last_success_at']),last_error=row['last_error'])


class PostgresBinanceSquareRepository:
    def __init__(self): self.init_schema()

    @contextmanager
    def _connect(self):
        with connect_postgres(schema='main',application_name='odaily-binance-square') as conn:
            with postgres_transaction(conn): yield conn

    def init_schema(self):
        self.initialize_schema()

    @staticmethod
    def initialize_schema():
        with connect_postgres(schema='main',application_name='odaily-binance-square-migrate') as conn:
            apply_schema_migrations(conn,schema='main',component='binance_square',migrations=(
                PostgresMigration(1,'binance_square_initial',sha256(SCHEMA_SQL.encode()).hexdigest(),lambda c:c.execute(SCHEMA_SQL)),
                PostgresMigration(2,'binance_square_external_error_counter',sha256(b'ALTER TABLE binance_square_attempts ADD COLUMN IF NOT EXISTS odaily_external_error_counted integer NOT NULL DEFAULT 0').hexdigest(),lambda c:c.execute('ALTER TABLE binance_square_attempts ADD COLUMN IF NOT EXISTS odaily_external_error_counted integer NOT NULL DEFAULT 0')),
            ))

    def get_settings(self):
        with self._connect() as c: row=c.execute("SELECT * FROM binance_square_settings WHERE singleton_key='global'").fetchone()
        if not row: raise RuntimeError('币安广场数据表尚未初始化')
        return BinanceSquareSettings(enabled=bool(row['enabled']),interval_seconds=int(row['interval_seconds']),worker_status=row['worker_status'],worker_last_seen_at=_dt(row['worker_last_seen_at']),updated_at=_dt(row['updated_at']))

    def list_accounts(self,*,include_disabled=False):
        with self._connect() as c: rows=c.execute('SELECT * FROM binance_square_accounts '+('' if include_disabled else 'WHERE enabled=true ')+'ORDER BY enabled DESC,slug_lower').fetchall()
        return [_account(r) for r in rows]

    def set_worker_status(self,status):
        with self._connect() as c: c.execute("UPDATE binance_square_settings SET worker_status=%s,worker_last_seen_at=now() WHERE singleton_key='global'",(status,))

    def update_account_identity(self,account_id,post):
        with self._connect() as c: c.execute("UPDATE binance_square_accounts SET square_uid=coalesce(%s,square_uid),display_name=coalesce(nullif(%s,''),display_name),updated_at=now() WHERE id=%s",(post.square_uid,post.display_name,account_id))

    def mark_seeded(self,account,post_ids):
        with self._connect() as c:
            with c.cursor() as cursor:
                cursor.executemany('INSERT INTO binance_square_seen_posts(post_id,account_id,seeded) VALUES(%s,%s,true) ON CONFLICT(post_id) DO NOTHING',[(p,account.id) for p in post_ids])
            c.execute('UPDATE binance_square_accounts SET seeded_at=now(),updated_at=now() WHERE id=%s',(account.id,))

    def unseen_post_ids(self,post_ids):
        if not post_ids:return set()
        with self._connect() as c: rows=c.execute('SELECT post_id FROM binance_square_seen_posts WHERE post_id=ANY(%s)',(post_ids,)).fetchall()
        return set(post_ids)-{str(r['post_id']) for r in rows}

    def mark_seen(self,account_id,post_id):
        with self._connect() as c:c.execute('INSERT INTO binance_square_seen_posts(post_id,account_id,seeded) VALUES(%s,%s,false) ON CONFLICT(post_id) DO NOTHING',(post_id,account_id))

    def save_task(self,account,post):
        name=(account.write_name or post.display_name or post.username or account.slug).strip(); metadata={'platform':BINANCE_SQUARE_SOURCE,'account_id':account.id,'account_username':account.slug,'author_username':post.username or account.slug,'author_display_name':post.display_name,'effective_author_name':name,'media_urls':post.media_urls}; raw={'platform':BINANCE_SQUARE_SOURCE,'post':post.raw_payload}
        with self._connect() as c:
            row=c.execute("INSERT INTO tasks(source,source_item_id,source_url,title,content,published_at,raw_payload,metadata,status) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,'pending') ON CONFLICT(source,source_item_id) DO UPDATE SET source_url=excluded.source_url RETURNING id",(BINANCE_SQUARE_SOURCE,post.post_id,post.url,f'{name}：{post.text[:80]}',post.text,_dt(post.published_at),json.dumps(raw,ensure_ascii=False),json.dumps(metadata,ensure_ascii=False))).fetchone()
        if row is None:raise RuntimeError(f'无法保存币安广场任务: {post.post_id}')
        return int(row['id'])

    def record_attempt(self,stats,*,started_at,finished_at):
        with self._connect() as c:
            c.execute('INSERT INTO binance_square_attempts(account_id,slug_lower,status,candidate_count,seeded_count,new_count,saved_count,error,metadata,started_at,finished_at) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)',(stats.account.id,stats.account.slug_lower,stats.status,stats.candidate_count,stats.seeded_count,stats.new_count,stats.saved_count,stats.error,json.dumps(stats.metadata),started_at,finished_at))
            c.execute("UPDATE binance_square_accounts SET last_polled_at=%s,last_success_at=CASE WHEN %s='success' THEN %s ELSE last_success_at END,last_error=CASE WHEN %s='success' THEN NULL ELSE %s END,updated_at=%s WHERE id=%s",(finished_at,stats.status,finished_at,stats.status,stats.error,finished_at,stats.account.id))


def create_binance_square_repository(path=None):
    if path is not None: raise ValueError('PostgreSQL Binance Square repository does not accept a SQLite path')
    if load_storage_settings().backend=='postgres': return PostgresBinanceSquareRepository()
    from .repository import BinanceSquareRepository
    return BinanceSquareRepository(load_storage_settings().sqlite_path)
